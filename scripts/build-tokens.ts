/**
 * Generates src/styles/tokens.css from src/tokens/tokens.ts.
 *   node scripts/build-tokens.ts          write the file
 *   node scripts/build-tokens.ts --check  fail if the committed file is stale (CI)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { primitive, semantic } from '../src/tokens/tokens.ts';

const OUT = fileURLToPath(new URL('../src/styles/tokens.css', import.meta.url));
const PREFIX = '--gds';

const kebab = (s: string) => s.replace(/[A-Z]/g, (m) => `-${m.toLowerCase()}`);

function flatten(obj: object, path: string[] = []): [string, string][] {
  return Object.entries(obj).flatMap(([key, value]) =>
    typeof value === 'object' && value !== null
      ? flatten(value as object, [...path, kebab(key)])
      : [[`${PREFIX}-${[...path, kebab(key)].join('-')}`, String(value)] as [string, string]],
  );
}

const block = (selector: string, vars: [string, string][], indent = '  ') =>
  `${indent}${selector} {\n${vars.map(([k, v]) => `${indent}  ${k}: ${v};`).join('\n')}\n${indent}}`;

const themeVars = (theme: Record<string, string>) =>
  Object.entries(theme).map(([k, v]) => [`${PREFIX}-${k}`, v] as [string, string]);

const css = `/* Generated by scripts/build-tokens.ts from src/tokens/tokens.ts. Do not edit by hand. */
@layer gds.tokens {
${block(':root', [...flatten(primitive), ...themeVars(semantic.light), ['color-scheme', 'light']])}

  @media (prefers-color-scheme: dark) {
${block(':root:not([data-theme="light"])', [...themeVars(semantic.dark), ['color-scheme', 'dark']], '    ')}
  }

${block('[data-theme="dark"]', [...themeVars(semantic.dark), ['color-scheme', 'dark']])}

${block('[data-theme="light"]', [...themeVars(semantic.light), ['color-scheme', 'light']])}
}
`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(OUT, 'utf8');
  } catch {
    /* missing counts as stale */
  }
  if (current !== css) {
    console.error('src/styles/tokens.css is out of date. Run `npm run tokens` and commit the result.');
    process.exit(1);
  }
  console.log('tokens.css is up to date.');
} else {
  writeFileSync(OUT, css);
  console.log(`Wrote ${OUT}`);
}
